  function solveSunLongitude(target, jdeGuess) {
    var jde = jdeGuess;
    for (var i = 0; i < 20; i++) {
      var lon = sunLongitude(jde);
      var diff = target - lon; diff = ((diff + 180) % 360 + 360) % 360 - 180;
      if (Math.abs(diff) < 1e-7) break;
      jde += diff / 360 * 365.2422; // 태양은 하루 약 0.9856°
    }
    return jde;
  }

