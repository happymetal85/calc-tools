  function jdFromDate(y, m, d) {
    if (m <= 2) { y -= 1; m += 12; }
    var A = Math.floor(y / 100), B = 2 - A + Math.floor(A / 4);
    return Math.floor(365.25 * (y + 4716)) + Math.floor(30.6001 * (m + 1)) + d + B - 1524.5;
  }
  function dateFromJd(jd) {
    jd += 0.5;
    var Z = Math.floor(jd), F = jd - Z, A = Z;
    if (Z >= 2299161) { var a = Math.floor((Z - 1867216.25) / 36524.25); A = Z + 1 + a - Math.floor(a / 4); }
    var B = A + 1524, C = Math.floor((B - 122.1) / 365.25), D = Math.floor(365.25 * C), E = Math.floor((B - D) / 30.6001);
    var day = B - D - Math.floor(30.6001 * E) + F;
    var month = E < 14 ? E - 1 : E - 13;
    var year = month > 2 ? C - 4716 : C - 4715;
    var di = Math.floor(day), frac = day - di;
    var secs = Math.round(frac * 86400);
    var h = Math.floor(secs / 3600), mi = Math.floor((secs % 3600) / 60), s = secs % 60;
    if (h === 24) { h = 23; mi = 59; s = 59; }
    return { y: year, m: month, d: di, h: h, mi: mi, s: s };
  }

